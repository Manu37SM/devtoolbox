import type { TransformResult } from "@/lib/tool-transform";
import type { SshConfigGeneratorOptions } from "./schema";

interface HostLine {
  aliases: string[];
  user?: string;
  host?: string;
  port?: number;
  extras: Record<string, string[]>;
  line: number;
}

const KNOWN = new Set(["jump", "key", "L", "R", "D", "forward", "agent", "timeout", "proxycommand"]);

function parseLine(text: string, line: number): HostLine {
  const tokens = text.trim().split(/\s+/);
  const eq = tokens.findIndex((t, i) => i > 0 && /^[A-Za-z]+=/.test(t));
  const head = eq < 0 ? tokens : tokens.slice(0, eq);
  const optTokens = eq < 0 ? [] : tokens.slice(eq);
  const fail = (m: string): never => {
    throw Object.assign(new Error(`Line ${line}: ${m}`), { line });
  };
  let target: string | undefined;
  let aliasTokens = head;
  const last = head[head.length - 1] ?? "";
  if (head.length > 1 && /[@.:]|^\d/.test(last) && !/^[\w*?-]+$/.test(last)) {
    target = last;
    aliasTokens = head.slice(0, -1);
  } else if (head.length > 1) {
    target = last;
    aliasTokens = head.slice(0, -1);
  }
  if (!aliasTokens.length || aliasTokens.some((a) => !/^!?[A-Za-z0-9_.*?-]+$/.test(a))) fail(`"${aliasTokens.join(" ")}" is not a valid host alias (letters, digits, . _ - and the wildcards * ?).`);
  const out: HostLine = { aliases: aliasTokens, extras: {}, line };
  if (target) {
    let rest = target;
    const at = rest.lastIndexOf("@");
    if (at >= 0) {
      out.user = rest.slice(0, at);
      rest = rest.slice(at + 1);
      if (!out.user) fail("The user before @ is empty.");
    }
    const pm = /^(\[[^\]]+\]|[^:]+)(?::(\d+))?$/.exec(rest);
    if (!pm) return fail(`"${target}" is not a valid [user@]host[:port].`);
    out.host = (pm[1] ?? "").replace(/^\[|\]$/g, "");
    if (pm[2]) {
      out.port = Number(pm[2]);
      if (out.port < 1 || out.port > 65535) fail(`Port ${pm[2]} is out of range (1-65535).`);
    }
  }
  for (const t of optTokens) {
    const m = /^([A-Za-z]+)=(.+)$/.exec(t);
    if (!m) fail(`Cannot read "${t}". Options look like key=value.`);
    const k = m![1] as string;
    if (!KNOWN.has(k)) fail(`Unknown option "${k}". Use jump, key, L, R, D, agent, timeout or proxycommand.`);
    (out.extras[k] ??= []).push(m![2] as string);
  }
  return out;
}


export function generateSshConfig(input: string, options: Partial<SshConfigGeneratorOptions>): TransformResult {
  const o: SshConfigGeneratorOptions = {
    defaultUser: options.defaultUser ?? "",
    defaultKey: options.defaultKey ?? "",
    identitiesOnly: options.identitiesOnly ?? true,
    addKeysToAgent: options.addKeysToAgent ?? false,
    useKeychain: options.useKeychain ?? false,
    forwardAgent: options.forwardAgent ?? false,
    keepAlive: options.keepAlive ?? 60,
    compression: options.compression ?? false,
    multiplexing: options.multiplexing ?? false,
    hostKeyChecking: options.hostKeyChecking ?? "default",
    globalBlock: options.globalBlock ?? true,
    comments: options.comments ?? true,
  };
  const lines = input.split(/\r?\n/);
  const hosts: HostLine[] = [];
  try {
    lines.forEach((raw, i) => {
      const t = raw.replace(/\s+#.*$/, "").trim();
      if (!t || t.startsWith("#")) return;
      hosts.push(parseLine(t, i + 1));
    });
  } catch (e) {
    const err = e as Error & { line?: number };
    return { output: "", error: { message: err.message, line: err.line } };
  }
  if (!hosts.length && !o.globalBlock) return { output: "", error: null };

  const seen = new Map<string, number>();
  for (const h of hosts)
    for (const a of h.aliases) {
      if (seen.has(a)) return { output: "", error: { message: `Line ${h.line}: alias "${a}" is already defined on line ${seen.get(a)}.`, line: h.line } };
      seen.set(a, h.line);
    }
  for (const h of hosts) {
    for (const j of h.extras.jump ?? []) {
      for (const hop of j.split(",")) {
        const name = hop.replace(/^.*@/, "").replace(/:\d+$/, "");
        if (!seen.has(hop) && !/[@.:]/.test(hop)) return { output: "", error: { message: `Line ${h.line}: jump host "${hop}" is not defined above. Add a line for it or use user@host.`, line: h.line } };
        if (h.aliases.includes(name)) return { output: "", error: { message: `Line ${h.line}: a host cannot jump through itself.`, line: h.line } };
      }
    }
  }

  const out: string[] = [];
  if (o.comments) out.push("# Generated by DevToolbox. SSH uses the FIRST value it finds for each setting,", "# so specific hosts come first and 'Host *' comes last.", "");
  for (const h of hosts) {
    const user = h.user ?? "";
    const wildcard = h.aliases.some((a) => /[*?]/.test(a));
    if (o.comments) out.push(`# ${h.aliases.join(", ")}${h.host ? ` -> ${h.host}` : ""}`);
    out.push(`Host ${h.aliases.join(" ")}`);
    if (h.host) out.push(`    HostName ${h.host}`);
    else if (!wildcard) out.push(`    HostName ${h.aliases[0]}`);
    if (user) out.push(`    User ${user}`);
    if (h.port) out.push(`    Port ${h.port}`);
    for (const k of h.extras.key ?? []) out.push(`    IdentityFile ${k}`);
    if (h.extras.key?.length && o.identitiesOnly) out.push("    IdentitiesOnly yes");
    if (h.extras.jump?.length) out.push(`    ProxyJump ${h.extras.jump.join(",")}`);
    for (const p of h.extras.proxycommand ?? []) out.push(`    ProxyCommand ${p}`);
    for (const f of h.extras.L ?? []) out.push(`    LocalForward ${f.replace(/^(\d+):/, "$1 ").replace(/^(\d+) ([^:]+:\d+)$/, "$1 $2")}`);
    for (const f of h.extras.R ?? []) out.push(`    RemoteForward ${f.replace(/^(\d+):/, "$1 ")}`);
    for (const d of h.extras.D ?? []) out.push(`    DynamicForward ${d}`);
    if (h.extras.agent) out.push(`    ForwardAgent ${/^(1|yes|true|on)$/i.test(h.extras.agent[0] ?? "") ? "yes" : "no"}`);
    if (h.extras.timeout) out.push(`    ConnectTimeout ${h.extras.timeout[0]}`);
    out.push("");
  }

  if (o.globalBlock) {
    const g: string[] = [];
    if (o.defaultUser.trim()) g.push(`User ${o.defaultUser.trim()}`);
    if (o.defaultKey.trim()) g.push(`IdentityFile ${o.defaultKey.trim()}`);
    if (o.defaultKey.trim() && o.identitiesOnly) g.push("IdentitiesOnly yes");
    if (o.addKeysToAgent) g.push("AddKeysToAgent yes");
    if (o.useKeychain) g.push("UseKeychain yes");
    if (o.forwardAgent) g.push("ForwardAgent yes");
    if (o.keepAlive > 0) g.push(`ServerAliveInterval ${o.keepAlive}`, "ServerAliveCountMax 3");
    if (o.compression) g.push("Compression yes");
    if (o.hostKeyChecking !== "default") g.push(`StrictHostKeyChecking ${o.hostKeyChecking}`);
    if (o.multiplexing) g.push("ControlMaster auto", "ControlPath ~/.ssh/cm-%r@%h:%p", "ControlPersist 10m");
    if (g.length) {
      if (o.comments) out.push("# Defaults for every host");
      out.push("Host *", ...g.map((x) => `    ${x}`), "");
    }
  }
  if (o.hostKeyChecking === "no" && o.comments) out.push("# WARNING: StrictHostKeyChecking no disables protection against man-in-the-middle attacks.", "");
  while (out[out.length - 1] === "") out.pop();
  return { output: out.join("\n") + "\n", error: null };
}
