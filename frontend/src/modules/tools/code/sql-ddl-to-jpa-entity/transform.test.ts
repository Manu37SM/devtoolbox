import { describe, expect, it } from "vitest";
import { javaType, parseDdl, runSqlDdlToJpaEntity } from "./transform";
import type { SqlDdlToJpaEntityOptions } from "./schema";

const base: SqlDdlToJpaEntityOptions = { target: "jakarta", lombok: true, idStrategy: "auto", relations: false, packageName: "com.acme.domain" };
const run = (s: string, o: Partial<SqlDdlToJpaEntityOptions> = {}) => runSqlDdlToJpaEntity(s, { ...base, ...o });

const ORACLE = `CREATE TABLE app.customers (
  customer_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR2(320 CHAR) NOT NULL UNIQUE,
  balance NUMBER(12,2) DEFAULT 0 NOT NULL,
  created_at DATE DEFAULT SYSDATE,
  notes CLOB,
  kyc_ok NUMBER(1)
);
CREATE TABLE orders (
  id NUMBER(10) NOT NULL,
  customer_id NUMBER(19) NOT NULL,
  placed_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT pk_orders PRIMARY KEY (id),
  CONSTRAINT fk_orders_cust FOREIGN KEY (customer_id) REFERENCES app.customers (customer_id)
);`;

describe("parseDdl", () => {
  it("parses columns, sizes, nullability, identity and constraints", () => {
    const [c, o] = parseDdl(ORACLE);
    expect(c).toMatchObject({ schema: "app", name: "customers", primaryKey: ["customer_id"] });
    expect(c!.columns[0]).toMatchObject({ name: "customer_id", type: "NUMBER", precision: 19, identity: true, primaryKey: true });
    expect(c!.columns[1]).toMatchObject({ name: "email", type: "VARCHAR2", precision: 320, nullable: false, unique: true });
    expect(c!.columns[2]).toMatchObject({ precision: 12, scale: 2, nullable: false });
    expect(o!.primaryKey).toEqual(["id"]);
    expect(o!.columns[1]!.references).toEqual({ table: "customers", column: "customer_id" });
    expect(o!.columns[2]!.type).toBe("TIMESTAMP WITH TIME ZONE");
  });
  it("handles MySQL backticks, AUTO_INCREMENT and Postgres serial", () => {
    expect(parseDdl("CREATE TABLE `t` (`id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT, PRIMARY KEY (`id`))")[0]!.columns[0]).toMatchObject({ name: "id", identity: true, primaryKey: true });
    expect(parseDdl("create table if not exists x (id bigserial primary key, data jsonb)")[0]!.columns[0]!.identity).toBe(true);
  });
});

describe("javaType", () => {
  const col = (type: string, precision?: number, scale?: number) => ({ name: "c", type, precision, scale, nullable: true, primaryKey: false, unique: false, identity: false });
  it("maps numeric precision sensibly", () => {
    expect(javaType(col("NUMBER", 9), true).type).toBe("Integer");
    expect(javaType(col("NUMBER", 19), true).type).toBe("Long");
    expect(javaType(col("NUMBER", 38), true).type).toBe("BigInteger");
    expect(javaType(col("NUMBER", 12, 2), true).type).toBe("BigDecimal");
    expect(javaType(col("NUMBER"), true).type).toBe("BigDecimal");
  });
  it("treats Oracle DATE as a timestamp and maps time zones", () => {
    expect(javaType(col("DATE"), true).type).toBe("LocalDateTime");
    expect(javaType(col("DATE"), false).type).toBe("LocalDate");
    expect(javaType(col("TIMESTAMPTZ"), false).type).toBe("OffsetDateTime");
    expect(javaType(col("TIMESTAMP WITHOUT TIME ZONE"), false).type).toBe("LocalDateTime");
    expect(javaType(col("TINYINT", 1), false).type).toBe("Boolean");
  });
});

describe("runSqlDdlToJpaEntity", () => {
  it("generates Jakarta entities with Lombok, identity ids and column metadata", () => {
    const out = run(ORACLE).output;
    expect(out).toContain("package com.acme.domain;");
    expect(out).toContain('@Table(name = "customers", schema = "app")');
    expect(out).toContain("public class Customer {");
    expect(out).toContain("@Id\n    @GeneratedValue(strategy = GenerationType.IDENTITY)\n    @Column(name = \"customer_id\")\n    private Long customerId;");
    expect(out).toContain('@Column(name = "email", nullable = false, unique = true, length = 320)\n    private String email;');
    expect(out).toContain('@Column(name = "balance", nullable = false, precision = 12, scale = 2)\n    private BigDecimal balance;');
    expect(out).toContain("// Oracle DATE also stores a time of day");
    expect(out).toContain("@Lob\n    @Column(name = \"notes\")");
    expect(out).toContain("// FK -> customers(customer_id)");
    expect(out).toContain("import jakarta.persistence.Entity;");
    expect(out).toContain("public class Order {");
  });
  it("maps foreign keys to @ManyToOne when relations are on", () => {
    const out = run(ORACLE, { relations: true }).output;
    expect(out).toContain('@ManyToOne(fetch = FetchType.LAZY)\n    @JoinColumn(name = "customer_id", nullable = false)\n    private Customer customer;');
  });
  it("supports sequences, javax, records and plain getters", () => {
    expect(run("CREATE TABLE items (id NUMBER(10) PRIMARY KEY)", { idStrategy: "sequence" }).output).toContain('@SequenceGenerator(name = "items_seq", sequenceName = "ITEMS_SEQ", allocationSize = 1)');
    expect(run("CREATE TABLE items (id INT PRIMARY KEY)", { target: "javax" }).output).toContain("import javax.persistence.Id;");
    expect(run("CREATE TABLE items (id INT PRIMARY KEY, name TEXT)", { target: "record" }).output).toContain("public record Item(\n    Integer id,\n    String name\n)");
    const plain = run("CREATE TABLE items (id INT PRIMARY KEY, name VARCHAR(50))", { lombok: false }).output;
    expect(plain).toContain("public String getName() {");
    expect(plain).toContain("protected Item() {");
  });
  it("generates an @EmbeddedId class for composite keys", () => {
    const out = run("CREATE TABLE order_lines (order_id BIGINT, line_no INT, qty INT NOT NULL, PRIMARY KEY (order_id, line_no))", { lombok: false }).output;
    expect(out).toContain("@EmbeddedId\n    private OrderLineId id;");
    expect(out).toContain("public class OrderLineId implements Serializable {");
    expect(out).toContain("return Objects.equals(orderId, other.orderId) && Objects.equals(lineNo, other.lineNo);");
  });
  it("errors without CREATE TABLE", () => {
    expect(run("SELECT 1").error?.message).toContain("No CREATE TABLE");
  });
});
