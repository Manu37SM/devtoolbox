"use client";

import { useMemo, useState } from "react";
import { OutputPane } from "@/components/tools/OutputPane";
import { DualPane } from "@/components/tools/DualPane";
import { ToolInput } from "@/components/tools/ToolInput";

import { runSqlDdlToJpaEntity } from "./transform";
import type { SqlDdlToJpaEntityOptions } from "./schema";

type Options = SqlDdlToJpaEntityOptions;

const defaultOptions: Options = {"target":"jakarta","idStrategy":"auto","lombok":true,"relations":false,"packageName":"com.example.domain"} as Options;

export function SqlDdlToJpaEntityToolView() {
  const [input, setInput] = useState("CREATE TABLE customers (\n  customer_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n  email VARCHAR2(320 CHAR) NOT NULL UNIQUE,\n  balance NUMBER(12,2) DEFAULT 0 NOT NULL,\n  created_at DATE DEFAULT SYSDATE\n);\n\nCREATE TABLE orders (\n  id NUMBER(19) NOT NULL,\n  customer_id NUMBER(19) NOT NULL,\n  status VARCHAR2(20) NOT NULL,\n  placed_at TIMESTAMP WITH TIME ZONE,\n  CONSTRAINT pk_orders PRIMARY KEY (id),\n  CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (customer_id)\n);");
  const [options, setOptions] = useState<Options>(defaultOptions);

  const result = useMemo(() => runSqlDdlToJpaEntity(input, options), [input, options]);

  return (
    <div className="flex h-full flex-col gap-3">
      <div className="flex flex-wrap items-center gap-2">
        <label className="flex items-center gap-1.5 text-sm text-text-secondary">
          Target
          <select
            className="rounded-sm border border-border-default bg-bg-raised px-1.5 py-1"
            value={options.target}
            onChange={(e) => setOptions((o) => ({ ...o, target: e.target.value as Options["target"] }))}
          >
            <option value="jakarta">{"JPA (jakarta)"}</option>
            <option value="javax">{"JPA (javax)"}</option>
            <option value="record">{"Java record"}</option>
          </select>
        </label>
        <label className="flex items-center gap-1.5 text-sm text-text-secondary">
          Id
          <select
            className="rounded-sm border border-border-default bg-bg-raised px-1.5 py-1"
            value={options.idStrategy}
            onChange={(e) => setOptions((o) => ({ ...o, idStrategy: e.target.value as Options["idStrategy"] }))}
          >
            <option value="auto">{"Detect"}</option>
            <option value="identity">{"IDENTITY"}</option>
            <option value="sequence">{"SEQUENCE"}</option>
            <option value="uuid">{"UUID"}</option>
            <option value="none">{"Assigned"}</option>
          </select>
        </label>
        <label className="flex items-center gap-1.5 text-sm text-text-secondary">
          <input type="checkbox" checked={options.lombok} onChange={(e) => setOptions((o) => ({ ...o, lombok: e.target.checked }))} />
          Lombok
        </label>
        <label className="flex items-center gap-1.5 text-sm text-text-secondary">
          <input type="checkbox" checked={options.relations} onChange={(e) => setOptions((o) => ({ ...o, relations: e.target.checked }))} />
          Foreign keys as @ManyToOne
        </label>
        <label className="flex items-center gap-1.5 text-sm text-text-secondary">
          Package
          <input
            type="text"
            value={options.packageName}
            onChange={(e) => setOptions((o) => ({ ...o, packageName: e.target.value }))}
            placeholder="com.acme.domain"
            aria-label="Package"
            className="w-40 rounded-sm border border-border-default bg-bg-raised px-1.5 py-1 font-mono"
          />
        </label>
      </div>
      <div className="min-h-0 flex-1">
        <DualPane
          input={
            <div className="flex h-full flex-col gap-2">
              <label className="text-sm font-medium text-text-secondary">CREATE TABLE statements</label>
              <ToolInput
                value={input}
                onChange={(e) => setInput(e.target.value)}
                placeholder="CREATE TABLE orders (...)"
                aria-label="CREATE TABLE statements"
                className="font-mono"
              />
            </div>
          }
          output={<OutputPane label="Output" value={result.output} error={result.error?.message ?? null} placeholder="Result will appear here" />}
        />
      </div>
    </div>
  );
}
