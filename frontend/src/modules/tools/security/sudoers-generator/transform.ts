import type { TransformResult } from "@/lib/tool-transform";
import type { SudoersGeneratorOptions } from "./schema";

const USER = /^(%?[A-Za-z_][A-Za-z0-9_.-]*\$?|%#\d+|#\d+|\+[A-Za-z0-9_.-]+|ALL)$/;
const HOST = /^(ALL|[A-Za-z0-9_.*?-]+|\+[A-Za-z0-9_.-]+)(\s*,\s*(ALL|[A-Za-z0-9_.*?-]+))*$/;
const RU = "!?(ALL|[%#]?[A-Za-z0-9_.-]+)";
const RUNAS = new RegExp(`^${RU}(\\s*,\\s*${RU})*(\\s*:\\s*${RU}(\\s*,\\s*${RU})*)?$`);

/** Split on commas that are not escaped with a backslash. */
const splitCmds = (s: string) => s.split(/(?<!\\),/).map((c) => c.trim()).filter(Boolean);

export function sudoersGenerator(input: string, options: Partial<SudoersGeneratorOptions>): TransformResult {
  const o: SudoersGeneratorOptions = {
    host: options.host ?? "ALL", runAs: options.runAs ?? "ALL", noPasswd: options.noPasswd ?? false, noExec: options.noExec ?? true,
    setEnv: options.setEnv ?? false, logOutput: options.logOutput ?? false, useAliases: options.useAliases ?? false,
    timestampTimeout: options.timestampTimeout ?? -1, logfile: options.logfile ?? "", header: options.header ?? true,
  };
  const lines = input.split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));
  if (lines.length === 0) return { output: "", error: null };
  const fail = (message: string): TransformResult => ({ output: "", error: { message } });
  if (!HOST.test(o.host.trim())) return fail(`Host "${o.host}" is not valid (use ALL, a hostname, or a comma-separated list).`);
  if (!RUNAS.test(o.runAs.trim())) return fail(`Run-as "${o.runAs}" is not valid (use ALL, root, user:group, …).`);
  if (o.logfile && !/^\/[^\s"'\\]+$/.test(o.logfile)) return fail("Logfile must be an absolute path without spaces or quotes.");

  const warnings: string[] = [];
  const rules: { who: string; cmds: string[]; n: number }[] = [];
  for (const [i, line] of lines.entries()) {
    const idx = line.indexOf(":");
    if (idx < 1) return fail(`Line ${i + 1}: expected "user: /path/to/cmd, /other/cmd" — got "${line}".`);
    const who = line.slice(0, idx).trim();
    const cmds = splitCmds(line.slice(idx + 1));
    if (!USER.test(who)) return fail(`Line ${i + 1}: "${who}" is not a valid user, %group, #uid or +netgroup.`);
    if (cmds.length === 0) return fail(`Line ${i + 1}: no commands after the colon.`);
    for (const c of cmds) {
      if (/[\n\r]/.test(c)) return fail(`Line ${i + 1}: command contains a newline.`);
      const bin = c.split(/\s+/)[0]!.replace(/^!/, "");
      if (c !== "ALL" && !bin.startsWith("/") && bin !== "sudoedit" && !/^[A-Z][A-Z0-9_]*$/.test(bin))
        return fail(`Line ${i + 1}: "${c}" must start with an absolute path (sudoers matches full paths, not names found in $PATH).`);
      if (/[#]/.test(c)) return fail(`Line ${i + 1}: "#" in a command starts a comment in sudoers; escape it or avoid it.`);
      if (c === "ALL") warnings.push(`${who}: ALL grants every command — this is full root.`);
      else if (/[*?\[]/.test(c) && c.includes(" ")) warnings.push(`${who}: wildcard in arguments ("${c}") matches more than you expect — sudo's * also matches spaces and extra options.`);
      else if (/(^|\/)(bash|sh|zsh|dash|su|vi|vim|nano|less|more|man|find|awk|perl|python[0-9.]*|ruby|env|tar|rsync|git|tee|cp|mv|dd|chmod|chown|mount|docker|nmap|ssh|scp)(\s|$)/.test(c) && !o.noExec)
        warnings.push(`${who}: ${c.split(/\s+/)[0]} can spawn a shell or write arbitrary files — allowing it is effectively root.`);
      else if (/(^|\/)(bash|sh|zsh|dash|su|vi|vim|nano|less|more|man|find|awk|perl|python[0-9.]*|ruby|env|tar|rsync|git|tee|cp|mv|dd|chmod|chown|mount|docker|nmap|ssh|scp)(\s|$)/.test(c))
        warnings.push(`${who}: ${c.split(/\s+/)[0]} can still write arbitrary files or escalate even with NOEXEC.`);
    }
    if (o.noPasswd && cmds.includes("ALL")) warnings.push(`${who}: NOPASSWD plus ALL means anyone who gets this account is root with no further prompt.`);
    rules.push({ who, cmds, n: i + 1 });
  }
  const uniqueWho = new Set(rules.map((r) => r.who));
  if (uniqueWho.has("ALL")) warnings.push("A rule for ALL users applies to every account on the machine.");

  const tags = [o.noPasswd ? "NOPASSWD" : "PASSWD", o.noExec ? "NOEXEC" : "", o.setEnv ? "SETENV" : "", o.logOutput ? "LOG_OUTPUT" : ""].filter(Boolean);
  // PASSWD is sudo's default; omit the explicit tag unless it is the only way to override an earlier NOPASSWD.
  const tagStr = tags.filter((t) => t !== "PASSWD").join(": ");

  const out: string[] = [];
  if (o.header) {
    out.push("# Generated by DevToolbox. Save as /etc/sudoers.d/<name> (no dots or ~ in the name),");
    out.push("# then:  chmod 0440 /etc/sudoers.d/<name>  &&  visudo -cf /etc/sudoers.d/<name>");
    for (const w of [...new Set(warnings)]) out.push(`# WARNING: ${w}`);
    out.push("");
  }
  for (const who of uniqueWho) {
    if (o.timestampTimeout >= 0) out.push(`Defaults:${who} timestamp_timeout=${o.timestampTimeout}`);
    if (o.logfile) out.push(`Defaults:${who} logfile="${o.logfile}"`);
  }
  if (out.length && out[out.length - 1] !== "") out.push("");
  const aliases = new Map<string, string>();
  for (const r of rules) {
    const hostPart = o.host.trim().replace(/\s+/g, "");
    const runPart = o.runAs.trim().replace(/\s*:\s*/g, " : ").replace(/\s*,\s*/g, ", ");
    let spec = r.cmds.join(", ");
    if (o.useAliases) {
      const name = `CMDS_${r.who.replace(/^[%#+]/, "").replace(/[^A-Za-z0-9]/g, "_").toUpperCase()}_${r.n}`;
      aliases.set(name, spec);
      spec = name;
    }
    r.cmds = [spec];
    out.push(`${r.who} ${hostPart}=(${runPart}) ${tagStr ? `${tagStr}: ` : ""}${spec}`);
  }
  if (aliases.size) {
    const defs = [...aliases].map(([k, v]) => `Cmnd_Alias ${k} = ${v}`);
    const first = out.findIndex((l) => rules.some((r) => l.startsWith(`${r.who} `)));
    out.splice(first, 0, ...defs, "");
  }
  return { output: out.join("\n") + "\n", error: null };
}
